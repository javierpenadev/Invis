/*
 * Генераторы конфигов демонов. Пишутся в <base>/configs при каждом запуске
 * (истина — всегда в сгенерированном файле, prefs-редакторы появятся позже).
 * Модуль не зависит от Electron — используется и в рантайме, и в dev-проверках.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const blocklists = require('./blocklists');

const PORTS = {
    torSocks: 9050,
    torControl: 9051,
    torDns: 5400,
    dnscrypt: 9053,
    i2pHttp: 4444,
    i2pSocks: 4447,
    i2pConsole: 7070,
};

const fwd = (p) => p.split(path.sep).join('/');

/* Атомарная запись (SEC-9): демон при рестарте мог прочитать полусконфиг */
function writeAtomic(file, data) {
    const tmp = `${file}.tmp`;
    fs.writeFileSync(tmp, data, 'utf8');
    fs.renameSync(tmp, file);
}

/* Имена pluggable-транспортов → исполняемые файлы в bin/tor/.../pluggable_transports.
 * В комплекте только то, что реально лежит в bin (CLEAN-4): snowflake/webtunnel
 * не бандлились и генерировали битый torrc. */
const BRIDGE_PLUGINS = {
    obfs4: 'lyrebird.exe',
    conjure: 'conjure-client.exe',
};

/* Tor (mingw-сборка) не умеет в не-ASCII пути: «Couldn't create private data
 * directory». Для таких путей используем короткие 8.3 имена (FSO ShortPath). */
function shortPathSync(p) {
    try {
        const out = execFileSync('powershell', [
            '-NoProfile', '-NonInteractive', '-Command',
            `(New-Object -ComObject Scripting.FileSystemObject).GetFolder('${p.replace(/'/g, "''")}').ShortPath`,
        ], { encoding: 'utf8', windowsHide: true, timeout: 15000 });
        const short = out.trim();
        if (short && !/[^\x00-\x7F]/.test(short)) return short;
    } catch (e) { /* 8.3 отключены или ps не отработал — вернём как есть */ }
    return p;
}
const torPath = (p) => (/[^\x00-\x7F]/.test(p) ? shortPathSync(p) : p);

function torrc({ dataDir, bridges, pluginDir }) {
    const dd = fwd(torPath(dataDir));
    const lines = [
        '# generated by Invis — ручные правки будут перезаписаны',
        `SocksPort ${PORTS.torSocks}`,
        `ControlPort ${PORTS.torControl}`,
        'CookieAuthentication 1',
        'ClientOnly 1',
        'NoExec 1',
        `DataDirectory ${dd}`,
        `GeoIPFile ${dd}/geoip`,
        `GeoIPv6File ${dd}/geoip6`,
        'Log notice stdout',
    ];

    /* Мосты: строки вида "obfs4 1.2.3.4:443 cert=... iat-mode=0" (префикс Bridge опционален).
     * Транспорт определяется по первому слову первой строки. */
    if (bridges && bridges.use && Array.isArray(bridges.lines) && bridges.lines.length) {
        const clean = bridges.lines
            .map((l) => l.trim().replace(/^Bridge\s+/, ''))
            .filter((l) => l && !l.startsWith('#'));
        const transport = clean.length ? clean[0].split(/\s+/)[0] : '';
        /* Имя транспорта попадает в путь плагина — только строгие символы
         * (SEC-12): '..' и прочее отсекаем, блок мостов просто не пишем. */
        if (clean.length && /^[A-Za-z0-9_-]+$/.test(transport)) {
            const plugin = BRIDGE_PLUGINS[transport] || `${transport}-client.exe`;
            const pluginPath = fwd(torPath(path.join(pluginDir || '', plugin)));
            /* Плагина нет (не забандлен/опечатка) — мосты не пишем вовсе:
             * битый ClientTransportPlugin валит весь Tor (CLEAN-4) */
            if (fs.existsSync(path.join(pluginDir || '', plugin))) {
                lines.push('UseBridges 1');
                lines.push(`ClientTransportPlugin ${transport} exec "${pluginPath}"`);
                for (const l of clean) lines.push(`Bridge ${l}`);
            } else {
                lines.push(`# плагин транспорта «${transport}» (${plugin}) не найден — мосты отключены`);
            }
        }
    }
    /* Страны выхода: ограничиваем выходные узлы выбранными странами.
     * StrictNodes 1 — строго выбранные страны, иначе Tor молча уйдёт в другую */
    if (Array.isArray(bridges && bridges.exitCountries) && bridges.exitCountries.length) {
        const ccs = bridges.exitCountries
            .map((c) => String(c).toLowerCase().replace(/[^a-z]/g, ''))
            .filter((c) => c.length === 2);
        if (ccs.length) {
            lines.push(`ExitNodes ${ccs.map((c) => `{${c}}`).join(',')}`);
            lines.push('StrictNodes 1');
        }
    }
    lines.push('');
    return lines.join('\n');
}

