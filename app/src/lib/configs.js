const tomlList = (arr) => '[' + arr.map((s) => `'${String(s).replace(/'/g, "''")}'`).join(', ') + ']';

/* cfg — раздел dnscrypt из настроек (см. store.js DEFAULTS.dnscrypt) */
function dnscryptToml(listenPort = PORTS.dnscrypt, cfg = {}) {
    /* При перехвате системного DNS слушаем оба loopback'а: Windows может
     * слать запросы и на 127.0.0.1, и на ::1 */
    const listen = cfg.lanAccess
        ? ['0.0.0.0:' + listenPort, '[::]:' + listenPort]
        : (listenPort === 53
            ? ['127.0.0.1:' + listenPort, '[::1]:' + listenPort]
            : ['127.0.0.1:' + listenPort]);
    const manual = !cfg.autoMode && Array.isArray(cfg.servers) && cfg.servers.length;
    const bootstrap = Array.isArray(cfg.bootstrap) && cfg.bootstrap.length
        ? cfg.bootstrap : ['9.9.9.9:53', '8.8.8.8:53'];

    return `# generated by Invis — ручные правки будут перезаписаны
listen_addresses = ${tomlList(listen)}
${manual ? `server_names = ${tomlList(cfg.servers)}\n` : ''}max_clients = 250
ipv4_servers = true
ipv6_servers = false
dnscrypt_servers = ${cfg.dnscryptProto !== false}
doh_servers = ${cfg.dohProto !== false}
require_dnssec = ${Boolean(cfg.requireDnssec)}
require_nolog = ${cfg.requireNolog !== false}
require_nofilter = ${cfg.requireNofilter !== false}
force_tcp = ${Boolean(cfg.forceTcp)}
block_ipv6 = ${Boolean(cfg.blockIpv6)}
timeout = 5000
keepalive = 30
cert_refresh_delay = 240
bootstrap_resolvers = ${tomlList(bootstrap)}
ignore_system_dns = true
netprobe_timeout = -1
log_level = 0
log_file = ''
use_syslog = false
cache = ${cfg.cache !== false}
cache_size = 4096
cache_min_ttl = 2400
cache_max_ttl = 86400
blocked_query_response = 'refused'
${cfg.queryLog ? `
[query_log]
  file = 'query.log'
  format = 'tsv'
` : ''}${cfg.hasBlockedNames ? `
[blocked_names]
  blocked_names_file = 'blocked-names.txt'
` : ''}[sources]

  [sources.'public-resolvers']
  urls = ['https://raw.githubusercontent.com/DNSCrypt/dnscrypt-resolvers/master/v3/public-resolvers.md']
  cache_file = 'public-resolvers.md'
  minisign_key = '${RESOLVERS_MINISIGN_KEY}'
  refresh_delay = 72

  [sources.'relays']
  urls = ['https://raw.githubusercontent.com/DNSCrypt/dnscrypt-resolvers/master/v3/relays.md']
  cache_file = 'relays.md'
  minisign_key = '${RESOLVERS_MINISIGN_KEY}'
  refresh_delay = 72
`;
}

