/*
 * Пишет все конфиги и готовит каталоги данных.
 * geoip копируется в каталог данных Tor (в torrc пути идут внутрь DataDirectory).
 * dnscryptListen: 9053 (обычный режим) или 53 (перехват системного DNS).
 * dnscryptCfg — раздел dnscrypt настроек; torCfg — раздел tor (мосты).
 */
function buildAll({ configDir, torDataDir, i2pDataDir, geoipDir, i2pdContribDir,
                    dnscryptListen = PORTS.dnscrypt, dnscryptCfg = {}, torCfg = {}, torPluginDir }) {
    for (const dir of [configDir, torDataDir, i2pDataDir]) fs.mkdirSync(dir, { recursive: true });
    /* i2pd нужны reseed-сертификаты в <datadir>/certificates */
    const i2pCerts = path.join(i2pDataDir, 'certificates');
    if (i2pdContribDir && !fs.existsSync(i2pCerts)) {
        fs.cpSync(path.join(i2pdContribDir, 'certificates'), i2pCerts, { recursive: true });
    }
    /* geoip — рядом с данными Tor, один раз */
    for (const f of ['geoip', 'geoip6']) {
        const dst = path.join(torDataDir, f);
        if (geoipDir && !fs.existsSync(dst)) fs.copyFileSync(path.join(geoipDir, f), dst);
    }
    writeAtomic(path.join(configDir, 'torrc'), torrc({
        dataDir: torDataDir,
        bridges: {
            use: Boolean(torCfg.useBridges),
            lines: String(torCfg.bridgesText || '').split(/\r?\n/),
            exitCountries: torCfg.exitCountries,
        },
        pluginDir: torPluginDir,
    }));
    /* composeBlockedNames читает мегабайтные пресеты — один раз, не дважды */
    const blocked = blocklists.composeBlockedNames(configDir, dnscryptCfg);
    writeAtomic(path.join(configDir, 'dnscrypt-proxy.toml'), dnscryptToml(dnscryptListen, {
        ...dnscryptCfg,
        hasBlockedNames: Boolean(blocked),
    }));
    if (blocked) writeAtomic(path.join(configDir, 'blocked-names.txt'), blocked);
    else try { fs.unlinkSync(path.join(configDir, 'blocked-names.txt')); } catch (e) { /* не было */ }
    writeAtomic(path.join(configDir, 'i2pd.conf'), i2pdConf());
    return {
        torrc: path.join(configDir, 'torrc'),
        dnscryptToml: path.join(configDir, 'dnscrypt-proxy.toml'),
        i2pdConf: path.join(configDir, 'i2pd.conf'),
    };
}

module.exports = { PORTS, buildAll, shortPathSync };
